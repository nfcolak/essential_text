def make_markdown_cell(source: list[str]) -> dict:
    """Create an NBFormat v4 markdown cell."""
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": [s + "\n" for s in source],
    }


def make_code_cell(source: list[str]) -> dict:
    """Create an NBFormat v4 code cell."""
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [s + "\n" for s in source],
    }


